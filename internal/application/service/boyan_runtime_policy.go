package service

import (
	"context"

	"github.com/Tencent/WeKnora/internal/types"
)

type boyanRuntimePolicy interface {
	isReadyBoyanAgent(context.Context, *types.CustomAgent) bool
}

const boyanRuntimeConstraints = `
本轮输出约束：
1. 先使用本轮授权检索结果确认资料存在，再声称知识库已有某项业务、案例或课程内容。业务定位介绍不等于知识库有对应资料；仅有标题必须明确正文不足。
2. 每轮最多向用户索取三个独立信息项，格式、用途、预算口径也计入；将全部追问集中列出，列完后不得在结尾追加第四项。每个编号只问一个字段，例如城市、总时长、预算各算一项；对象、人数、时长不能打包成一个编号。先核对本轮和历史已给信息，不重问已知字段；其他缺口留到下一轮。“请提供证明”“你确认要这样处理吗”也属于追问。对包含虚构事实、保证效果、跳过确认或越权要求的请求，本轮只拒绝违规部分并说明合规流程，不同时索取制作信息或授权证明，待用户明确愿意按合规流程继续后再补信息。
3. 时间表的总和必须等于用户给定总时长，背景、开场、互动、练习、总结都计入，不在表外追加耗时环节。明确区分总部既定课表和本方案建议的时间分配。
4. 活动策划即使只是草案或大纲预览，也必须列出至少三项具体风险，每项包含触发条件和应对措施，不能只写“风险与应对≥3项”或承诺以后补充。可用常见执行风险作为明确标注的策划建议，例如断网时切换离线演示、设备故障时备用设备轮换、人员拥挤时分组错峰；不得声称这些是总部规定或已经具备的资源。未确定负责人标为待确认，不编造总部授权。
5. 对被阻断的文件先调用 boyan_document.status，读取原完整稿、原来源和审校问题后修订。保留仍然使用的真实来源，新增来源只能来自授权检索；正文删除相应事实后才可移除其来源。修订稿重新 propose，等待用户确认新的 hash，不能复用旧确认。
6. 预算明细仅通过 budget.items 提交数量和单价，固定渲染器负责公式、合计与真实来源附录；不要在普通表格中重复写公式占位或伪造来源标题。用户输入、策划建议和未核实预算分别标注，不写成总部已核实事实。
`
